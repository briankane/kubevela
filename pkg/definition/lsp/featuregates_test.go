var updateFeatureGates = flag.Bool("update-feature-gates", false, "rewrite featuregates_generated.go from the gates' source files")

const featureGatesFile = "featuregates_generated.go"

// featureGateSources are the files declaring the gates a KubeVela controller
// is built with, by the module each is in.
var featureGateSources = []struct{ source, module, file string }{
	{source: "kubevela", file: filepath.Join("..", "..", "features", "controller_features.go")},
	{source: "workflow", module: "github.com/kubevela/workflow", file: "pkg/features/controller_features.go"},
	{source: "multicluster", module: "github.com/oam-dev/cluster-gateway", file: "pkg/featuregates/featue_gate.go"},
}

// The table of gates is what their source files declare. Run
// go test ./pkg/definition/lsp -run TestFeatureGateDocs -update-feature-gates
// after a dependency bump.
func TestFeatureGateDocs(t *testing.T) {
	var gates []FeatureGateInfo
	for _, s := range featureGateSources {
		path := s.file
		if s.module != "" {
			out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", s.module).Output()
			require.NoError(t, err, s.module)
			path = filepath.Join(strings.TrimSpace(string(out)), s.file)
		}
		gates = append(gates, parseFeatureGates(t, path, s.source)...)
	}
	sort.Slice(gates, func(i, j int) bool { return gates[i].Name < gates[j].Name })
	if *updateFeatureGates {
		require.NoError(t, os.WriteFile(featureGatesFile, generatedFeatureGates(gates), 0o600))
		return
	}
	assert.Equal(t, gates, featureGateDocs, "run this test with -update-feature-gates")
}

// parseFeatureGates are the keys of the FeatureSpec maps a file declares,
// each described by the paragraph of its constant's comment that names it.
func parseFeatureGates(t *testing.T, path, source string) []FeatureGateInfo {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
	require.NoError(t, err)
	docs := map[string]string{}
	for _, d := range f.Decls {
		if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.CONST {
			for _, spec := range g.Specs {
				v := spec.(*ast.ValueSpec)
				docs[v.Names[0].Name] = v.Doc.Text()
			}
		}
	}
	var out []FeatureGateInfo
	ast.Inspect(f, func(n ast.Node) bool {
		lit, ok := n.(*ast.CompositeLit)
		if !ok {
			return true
		}
		if m, ok := lit.Type.(*ast.MapType); !ok || !isSelector(m.Value, "FeatureSpec") {
			return true
		}
		for _, e := range lit.Elts {
			if key, ok := e.(*ast.KeyValueExpr).Key.(*ast.Ident); ok {
				out = append(out, FeatureGateInfo{Name: key.Name, Source: source, Description: describeGate(key.Name, docs[key.Name])})
			}
		}
		return false
	})
	require.NotEmpty(t, out, path)
	return out
}

func isSelector(e ast.Expr, name string) bool {
	sel, ok := e.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == name
}

// describeGate is the paragraph of a doc comment that starts with the
// gate's name, else its first, the name dropped and the first letter raised.
func describeGate(name, doc string) string {
	var paragraphs []string
	for _, p := range strings.Split(doc, "\n\n") {
		if p = strings.Join(strings.Fields(p), " "); p != "" && !strings.HasPrefix(p, "owner:") {
			paragraphs = append(paragraphs, p)
		}
	}
	if len(paragraphs) == 0 {
		return ""
	}
	text := paragraphs[0]
	for _, p := range paragraphs {
		if strings.HasPrefix(p, name+" ") {
			text = p
			break
		}
	}
	text = strings.TrimPrefix(text, name+" ")
	return strings.ToUpper(text[:1]) + text[1:]
}

func generatedFeatureGates(gates []FeatureGateInfo) []byte {
	var b bytes.Buffer
	header, err := os.ReadFile(filepath.Join("..", "..", "..", "hack", "boilerplate.go.txt"))
	if err == nil {
		b.Write(header)
		b.WriteString("\n")
	}
	b.WriteString("// Code generated by TestFeatureGateDocs -update-feature-gates. DO NOT EDIT.\n\npackage lsp\n\n")
	b.WriteString("// featureGateDocs are the gates a KubeVela controller is built with, from their source files.\nvar featureGateDocs = []FeatureGateInfo{\n")
	for _, g := range gates {
		fmt.Fprintf(&b, "\t{Name: %q, Source: %q, Description: %q},\n", g.Name, g.Source, g.Description)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func TestDescribeGate(t *testing.T) {
	assert.Equal(t, "Enables the health subresource.", describeGate("HealthinessCheck", "owner: @x\nalpha: v1.1\n\nHealthinessCheck enables the\nhealth subresource.\n\nAdditionally, more."))
	assert.Equal(t, "Enable suspend on failure", describeGate("EnableSuspendOnFailure", "EnableSuspendOnFailure enable suspend on failure\n"))
	assert.Equal(t, "", describeGate("X", ""))
}

// The client is served every gate with where it is from and what it does.
func TestFeatureGatesRequest(t *testing.T) {
	c := newClient(t)
	var got FeatureGatesResult
	require.NoError(t, json.Unmarshal(c.response(c.send(MethodFeatureGates, struct{}{}, true))["result"], &got))
	by := map[string]FeatureGateInfo{}
	for _, g := range got.Gates {
		by[g.Name] = g
	}
	assert.Equal(t, "kubevela", by["EnableCelExpressions"].Source)
	assert.Equal(t, "workflow", by["EnableSuspendOnFailure"].Source)
	assert.Equal(t, "multicluster", by["SecretCache"].Source)
	assert.NotEmpty(t, by["ApplyResourceByReplace"].Description)
}
